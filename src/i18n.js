function normalizeLang(lang) {
  const value = String(lang || "").toLowerCase();
  return DICT[value] ? value : "uz";
}

function t(lang, key, vars = {}) {
  const pack = DICT[normalizeLang(lang)] || DICT.uz;
  let text = pack[key] || DICT.en[key] || key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

function natLabel(lang, value) {
  const pack = DICT[normalizeLang(lang)] || DICT.uz;
  return pack[`nat_${value}`] || value || "—";
}

function bundle(lang) {
  return DICT[normalizeLang(lang)];
}

module.exports = { DICT, t, natLabel, bundle, normalizeLang };
